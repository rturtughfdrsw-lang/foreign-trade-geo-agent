"""Offline prompt/strict-parser controls, never model-output evidence."""
import json
import unittest

import prompt as candidate

e = candidate.previous


class JsonPromptContractTests(unittest.TestCase):
    def test_only_requested_system_append_and_user_message_unchanged(self):
        original = e.phase2.strict((candidate.A3 / 'prompt.json').read_bytes())
        updated = candidate.messages()
        self.assertEqual(updated[0]['role'], original[0]['role'])
        self.assertEqual(updated[0]['content'], original[0]['content'] + candidate.JSON_ESCAPING)
        self.assertEqual(updated[1], original[1])
        self.assertEqual(len(updated), 2)

    def test_escaping_requirement_contains_literal_backslash_n(self):
        required = (
            'JSON STRING ESCAPING REQUIREMENT:',
            'The output must be valid JSON.',
            'The article field value is a JSON string.',
            r'Escape all newline characters inside the article string as \n.',
            'Do not output literal line breaks inside JSON string values.',
            'Do not use markdown code fences.',
            'Do not prepend explanations.',
            'Return exactly:\n\n{\n  "article": "..."\n}',
        )
        for instruction in required:
            with self.subTest(instruction=instruction):
                self.assertIn(instruction, candidate.messages()[0]['content'])

    def test_a3_boundary_preserved_in_full(self):
        self.assertTrue(candidate.SYSTEM.startswith(candidate.base.SYSTEM))
        self.assertIn(candidate.base.BOUNDARY, candidate.SYSTEM)
        self.assertEqual(candidate.BOUNDARY, candidate.base.BOUNDARY + candidate.JSON_ESCAPING)

    def test_model_parameters_remain_frozen(self):
        self.assertEqual(e.PARAMETERS, dict(model='deepseek-flash', temperature=0,
            thinking={'type': 'disabled'}, response_format={'type': 'json_object'}, max_tokens=3000))

    def test_valid_escaped_newlines_quotes_and_backslashes_roundtrip(self):
        # Authored fixture, not generated by an LLM and not a repaired response.
        article = e.p.CLEAN + '\n\nA quoted "fixture" with a literal \\ character.'
        encoded = json.dumps({'article': article}, ensure_ascii=False)
        self.assertNotIn('\n', encoded)
        self.assertIn(r'\n', encoded)
        self.assertEqual(e.phase2.strict(encoded), {'article': article})
        result = e.draft_layers(encoded)
        self.assertIsNone(result['first_failed_layer'])
        self.assertEqual(result['layers'][0]['status'], 'PASS')
        self.assertEqual(result['layers'][2]['status'], 'PENDING_RECORDED_EVIDENCE_AUDIT')

    def test_original_a4_response_still_rejected_without_repair(self):
        content = (candidate.OUT.parent / 'real-llm-draft-phase7a4/model-response.txt').read_bytes()
        with self.assertRaises(json.JSONDecodeError) as raised:
            e.phase2.strict(content)
        self.assertEqual(raised.exception.pos, 87)
        self.assertEqual(e.draft_layers(content.decode('utf-8'))['first_failed_layer'], 1)

    def test_unescaped_quotes_extra_fields_fences_and_duplicate_keys_rejected(self):
        invalid = ('{"article":"a "quoted" value"}', '{"article":"a","extra":1}',
                   '```json\n{"article":"a"}\n```', '{"article":"a","article":"b"}')
        for content in invalid:
            with self.subTest(content=content):
                self.assertEqual(e.draft_layers(content)['first_failed_layer'], 1)


if __name__ == '__main__':
    unittest.main()
